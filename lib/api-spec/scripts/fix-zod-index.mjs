// Orval's split mode rewrites lib/api-zod/src/index.ts to re-export both
// `./generated/api` (the Zod schemas) and `./generated/types` (TS types).
// Those two files share many symbol names, which produces TS2308 ambiguity
// errors on every codegen. We only need the schema barrel here; TS types are
// consumed via `@workspace/api-client-react/api.schemas` (web) or
// `@workspace/api-zod/types` (server) directly.
import { writeFileSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const target = resolve(here, "..", "..", "api-zod", "src", "index.ts");

const content = `// Zod runtime schemas generated by orval (used by the API server for request/response validation).
// TypeScript types are available via z.infer<typeof Schema> or by importing
// from @workspace/api-client-react/api.schemas for client-side usage.
export * from "./generated/api";
`;

writeFileSync(target, content, "utf8");
console.log("api-zod: pruned index.ts to schemas-only barrel");
